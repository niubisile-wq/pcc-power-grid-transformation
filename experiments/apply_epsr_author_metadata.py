"""Apply author-confirmed EPSR metadata to the submission form.

The input JSON is intentionally separate from the Markdown form so author
confirmations can be checked mechanically before the final manifest is rebuilt.
"""

from __future__ import annotations

import json
import subprocess
import sys
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
DEFAULT_INPUT = ROOT / "manuscript" / "EPSR_AUTHOR_METADATA_TEMPLATE.json"
AUTHOR_FORM = ROOT / "manuscript" / "EPSR_AUTHOR_INPUT_FORM.md"

REQUIRED_FIELDS = [
    "final_author_order",
    "full_names",
    "affiliations_and_postal_addresses",
    "author_affiliation_mapping",
    "corresponding_author",
    "corresponding_email",
    "orcid_identifiers",
    "credit_roles",
    "funding_statement",
    "competing_interests_statement",
    "acknowledgements",
    "generative_ai_disclosure",
    "all_author_approval",
    "not_under_review_elsewhere",
    "final_zenodo_concept_doi",
    "final_release_doi",
    "release_tag",
    "code_license",
    "source_data_license",
    "third_party_dataset_confirmation",
]

YES_NO_FIELDS = [
    "all_author_approval",
    "not_under_review_elsewhere",
    "third_party_dataset_confirmation",
]


def is_missing(value: object) -> bool:
    if value is None:
        return True
    if isinstance(value, str):
        stripped = value.strip()
        return not stripped or stripped.lower() in {"todo", "tbd", "unknown", "n/a?"}
    if isinstance(value, list):
        return not value or any(is_missing(item) for item in value)
    return False


def main() -> int:
    validation = subprocess.run(
        [sys.executable, "experiments/validate_epsr_author_metadata.py"],
        cwd=ROOT,
        text=True,
        capture_output=True,
    )
    if validation.returncode != 0:
        print(validation.stdout.strip())
        if validation.stderr:
            print(validation.stderr.strip())
        return validation.returncode

    data = json.loads(DEFAULT_INPUT.read_text(encoding="utf-8"))
    missing = [field for field in REQUIRED_FIELDS if is_missing(data.get(field))]
    invalid_yes_no = [
        field for field in YES_NO_FIELDS
        if str(data.get(field, "")).strip().lower() not in {"yes", "no"}
    ]

    if missing or invalid_yes_no:
        result = {
            "status": "not_applied",
            "missing_fields": missing,
            "invalid_yes_no_fields": invalid_yes_no,
            "input": str(DEFAULT_INPUT.relative_to(ROOT)),
            "target": str(AUTHOR_FORM.relative_to(ROOT)),
        }
        print(json.dumps(result, indent=2, ensure_ascii=False))
        return 2

    roles = data["credit_roles"]
    role_text = "; ".join(roles) if isinstance(roles, list) else str(roles)
    text = f"""# Author-supplied submission metadata

Completed from author-confirmed JSON metadata. Do not edit this file manually
after final archive freeze; update `manuscript/EPSR_AUTHOR_METADATA_TEMPLATE.json`
and rerun `experiments/apply_epsr_author_metadata.py` instead.

## Title page

- Final author order: {data["final_author_order"]}
- Full names exactly as submitted: {data["full_names"]}
- Affiliations and postal addresses: {data["affiliations_and_postal_addresses"]}
- Author–affiliation mapping: {data["author_affiliation_mapping"]}
- Corresponding author: {data["corresponding_author"]}
- Corresponding email: {data["corresponding_email"]}
- ORCID identifiers: {data["orcid_identifiers"]}

## CRediT contribution statement

For each author, confirm applicable roles: Conceptualization; Methodology; Software; Validation; Formal analysis; Investigation; Data curation; Writing—original draft; Writing—review and editing; Visualization; Supervision; Project administration; Funding acquisition.

- Zixuan Liu: {role_text}

## Declarations

- Funding source and grant number, or “This research received no specific grant from any funding agency in the public, commercial, or not-for-profit sectors”: {data["funding_statement"]}
- Competing interests, or “The authors declare that they have no known competing financial interests or personal relationships that could have appeared to influence the work reported in this paper”: {data["competing_interests_statement"]}
- Acknowledgements: {data["acknowledgements"]}
- Use of generative AI disclosure, if required by the journal’s current policy: {data["generative_ai_disclosure"]}
- All-author approval of manuscript and author order: {data["all_author_approval"]}
- Confirmation that the work is not under review elsewhere: {data["not_under_review_elsewhere"]}

## Archive freeze

- Final Zenodo concept DOI: {data["final_zenodo_concept_doi"]}
- Final release/version DOI: {data["final_release_doi"]}
- Release tag/version: {data["release_tag"]}
- License for original code: {data["code_license"]}
- License for original manuscript/figure source data: {data["source_data_license"]}
- Confirmation that third-party datasets are referenced rather than relicensed: {data["third_party_dataset_confirmation"]}
"""
    AUTHOR_FORM.write_text(text, encoding="utf-8")
    result = {
        "status": "applied",
        "input": str(DEFAULT_INPUT.relative_to(ROOT)),
        "target": str(AUTHOR_FORM.relative_to(ROOT)),
    }
    print(json.dumps(result, indent=2, ensure_ascii=False))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
